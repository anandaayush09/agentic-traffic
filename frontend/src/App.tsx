import { useCallback, useEffect, useState } from "react";
import "./App.css";
import { MapView } from "./MapView";
import { ApprovalQueue } from "./ApprovalQueue";
import { XaiPanel } from "./XaiPanel";
import { SignalControl } from "./SignalControl";
import { ReplayScrubber } from "./ReplayScrubber";
import { useTrafficFeed } from "./useTrafficFeed";
import staticSnapshot from "./public_demo_snapshot.json";
import {
  ApiError,
  approveIncident,
  getAuthConfig,
  getTrafficHistory,
  listIncidents,
  rejectIncident,
  requestDemoToken,
  setJunctionMode,
  submitIncident,
  type ControllerMode,
  type Incident,
  type TrafficSnapshot,
} from "./api";

// Where the API is. Resolved in order: the container's runtime setting (window.__ATLAS_CONFIG__,
// generated by nginx from ATLAS_API_BASE_URL -- one image, every environment), a build-time
// VITE_API_BASE_URL, then localhost for development. The header field stays editable regardless.
declare global {
  interface Window {
    __ATLAS_CONFIG__?: { apiBaseUrl?: string };
  }
}
const DEFAULT_API_BASE_URL =
  window.__ATLAS_CONFIG__?.apiBaseUrl ||
  (import.meta.env.VITE_API_BASE_URL as string | undefined) ||
  "http://localhost:8000";
const POLL_INTERVAL_MS = 3000;
const REPLAY_FRAME_INTERVAL_MS = 500;

// The demo buttons. Locations are corridor JUNCTION ids (the map keys incidents by
// junction): the live twin applies an accident/closure to every road entering that
// junction, so the effect is visible on the map. A sensor fault has no road effect.
const DEMO_INCIDENTS = {
  sensor_fault: { label: "Demo: sensor fault", junction: "42430333" },
  accident: { label: "Demo: accident", junction: "42430342" },
  closure: { label: "Demo: closure", junction: "42430338" },
} as const;
type DemoIncidentClass = keyof typeof DEMO_INCIDENTS;

// The public read-only demo (docs/design/10_deployment.md: "zero control endpoints,
// no bus, no LLM keys") is a SEPARATE build of this same app, not a config flag on
// the live one: `npm run build:demo` sets VITE_STATIC_DEMO=true, which makes this
// component load a real, frozen snapshot (scripts/export_public_demo_snapshot.py --
// real Supervisor graph runs against the real manhattan_midtown corridor, not
// fabricated data) with zero network calls and no mutating UI at all. The live/dev
// build (`npm run dev` / `npm run build`) is unaffected -- polls a real Cognitive
// API and keeps full approve/reject wiring, exactly as before.
const STATIC_DEMO = import.meta.env.VITE_STATIC_DEMO === "true";
const STATIC_INCIDENTS = staticSnapshot as Incident[];

// Incidents are polled (they change slowly). Live traffic arrives over a WebSocket the API
// pushes to, falling back to polling -- see useTrafficFeed. Neither is a fake feed: no live
// Kafka/Redpanda locally (same documented gap as every other bus-based service here), so the
// API itself is the source.
let demoIncidentCounter = 0;

function App() {
  const [apiBaseUrl, setApiBaseUrl] = useState(DEFAULT_API_BASE_URL);
  const [operatorToken, setOperatorToken] = useState("");
  const [incidents, setIncidents] = useState<Incident[]>(STATIC_DEMO ? STATIC_INCIDENTS : []);
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busyId, setBusyId] = useState<string | null>(null);
  const {
    roads,
    junctions,
    traffic: liveTraffic,
    unavailable: trafficUnavailable,
  } = useTrafficFeed(apiBaseUrl, !STATIC_DEMO);
  const [demoTokenAvailable, setDemoTokenAvailable] = useState(false);
  const [replayFrames, setReplayFrames] = useState<TrafficSnapshot[] | null>(null);
  const [replayIndex, setReplayIndex] = useState(0);
  const [replayPlaying, setReplayPlaying] = useState(false);
  const [replayLoading, setReplayLoading] = useState(false);
  const [replayError, setReplayError] = useState<string | null>(null);

  const refresh = useCallback(async () => {
    if (STATIC_DEMO) return; // nothing to poll -- the snapshot is loaded once, above
    try {
      const result = await listIncidents(apiBaseUrl);
      setIncidents(result);
      setError(null);
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err));
    }
  }, [apiBaseUrl]);

  useEffect(() => {
    if (STATIC_DEMO) return;
    refresh();
    const timer = setInterval(refresh, POLL_INTERVAL_MS);
    return () => clearInterval(timer);
  }, [refresh]);

  // Is the "Get demo token" button available? Only when the API was started with the demo
  // token enabled (`make demo` does; a bare API run does not). Failure just hides it.
  useEffect(() => {
    if (STATIC_DEMO) return;
    let cancelled = false;
    getAuthConfig(apiBaseUrl)
      .then((config) => {
        if (!cancelled) setDemoTokenAvailable(config.demo_token_enabled);
      })
      .catch(() => {
        if (!cancelled) setDemoTokenAvailable(false);
      });
    return () => {
      cancelled = true;
    };
  }, [apiBaseUrl]);

  // Replay playback: step through the recorded frames, stop at the end.
  useEffect(() => {
    if (!replayPlaying || !replayFrames) return;
    const timer = setInterval(() => {
      setReplayIndex((i) => {
        if (i + 1 >= replayFrames.length) {
          setReplayPlaying(false);
          return i;
        }
        return i + 1;
      });
    }, REPLAY_FRAME_INTERVAL_MS);
    return () => clearInterval(timer);
  }, [replayPlaying, replayFrames]);

  // While replaying, every panel that reads traffic shows the recorded frame, not live.
  const traffic: TrafficSnapshot | null = replayFrames
    ? (replayFrames[Math.min(replayIndex, replayFrames.length - 1)] ?? null)
    : liveTraffic;

  async function handleStartReplay() {
    setReplayLoading(true);
    setReplayError(null);
    try {
      const { frames } = await getTrafficHistory(apiBaseUrl);
      setReplayFrames(frames);
      setReplayIndex(0);
      setReplayPlaying(frames.length > 1);
    } catch (err) {
      setReplayError(err instanceof Error ? err.message : String(err));
    } finally {
      setReplayLoading(false);
    }
  }

  function handleExitReplay() {
    setReplayFrames(null);
    setReplayPlaying(false);
    setReplayIndex(0);
  }

  async function handleGetDemoToken() {
    try {
      setOperatorToken(await requestDemoToken(apiBaseUrl));
      setError(null);
    } catch (err) {
      setError(
        err instanceof ApiError ? `Demo token failed (${err.status}): ${err.message}` : String(err),
      );
    }
  }

  const selected = incidents.find((i) => i.incident_id === selectedId) ?? null;

  async function handleApprove(incidentId: string) {
    setBusyId(incidentId);
    try {
      await approveIncident(apiBaseUrl, operatorToken, incidentId);
      await refresh();
    } catch (err) {
      setError(err instanceof ApiError ? `Approve failed (${err.status}): ${err.message}` : String(err));
    } finally {
      setBusyId(null);
    }
  }

  async function handleReject(incidentId: string) {
    setBusyId(incidentId);
    try {
      await rejectIncident(apiBaseUrl, operatorToken, incidentId);
      await refresh();
    } catch (err) {
      setError(err instanceof ApiError ? `Reject failed (${err.status}): ${err.message}` : String(err));
    } finally {
      setBusyId(null);
    }
  }

  async function handleSetMode(tlsId: string, mode: ControllerMode) {
    setBusyId(tlsId);
    try {
      await setJunctionMode(apiBaseUrl, operatorToken, tlsId, mode);
    } catch (err) {
      setError(
        err instanceof ApiError ? `Mode change failed (${err.status}): ${err.message}` : String(err),
      );
    } finally {
      setBusyId(null);
    }
  }

  // The demo buttons name the Midtown corridor's junctions. On another network (a whole city) those
  // ids do not exist, so spread the three demo incidents over real junctions of the loaded one.
  function demoJunctionFor(incidentClass: DemoIncidentClass): string {
    const preferred = DEMO_INCIDENTS[incidentClass].junction;
    if (junctions.length === 0 || junctions.some((j) => j.id === preferred)) return preferred;
    const slot = (Object.keys(DEMO_INCIDENTS) as DemoIncidentClass[]).indexOf(incidentClass);
    return junctions[Math.floor(((slot + 1) * junctions.length) / 4)].id;
  }

  async function handleSubmitDemoIncident(incidentClass: DemoIncidentClass) {
    demoIncidentCounter += 1;
    const incidentId = `demo-${incidentClass}-${Date.now()}-${demoIncidentCounter}`;
    try {
      await submitIncident(apiBaseUrl, operatorToken, {
        incident_id: incidentId,
        class: incidentClass,
        status: "detected",
        confidence: 0.9,
        // Real manhattan_midtown corridor junction (matches MapView.tsx's
        // corridor_geometry.json), not a placeholder id -- the demo API server
        // (scripts/run_dashboard_demo_api.py) runs against this same real network.
        location: { link_ids: [demoJunctionFor(incidentClass)] },
      });
      await refresh();
      setSelectedId(incidentId);
    } catch (err) {
      setError(err instanceof ApiError ? `Submit failed (${err.status}): ${err.message}` : String(err));
    }
  }

  return (
    <div className="app">
      <header className="topbar">
        <h1>ATLAS Operations Dashboard</h1>
        {STATIC_DEMO ? (
          <div className="settings">
            <span className="demo-banner">
              Public read-only demo — replaying {STATIC_INCIDENTS.length} real recorded
              incidents (no live backend, no control actions)
            </span>
          </div>
        ) : (
          <div className="settings">
            <label>
              API base URL
              <input value={apiBaseUrl} onChange={(e) => setApiBaseUrl(e.target.value)} />
            </label>
            <label>
              Operator token
              <input
                type="password"
                placeholder="paste a JWT to approve/reject/submit"
                value={operatorToken}
                onChange={(e) => setOperatorToken(e.target.value)}
              />
            </label>
            {demoTokenAvailable && (
              <button type="button" onClick={handleGetDemoToken}>
                {operatorToken ? "Token set ✓" : "Get demo token"}
              </button>
            )}
            {(Object.keys(DEMO_INCIDENTS) as DemoIncidentClass[]).map((incidentClass) => (
              <button
                key={incidentClass}
                type="button"
                onClick={() => handleSubmitDemoIncident(incidentClass)}
              >
                {DEMO_INCIDENTS[incidentClass].label}
              </button>
            ))}
          </div>
        )}
      </header>

      {error && <div className="error-banner">{error}</div>}

      <main className="layout">
        <MapView
          incidents={incidents}
          selectedId={selectedId}
          onSelectIncident={setSelectedId}
          roads={STATIC_DEMO ? [] : roads}
          junctions={STATIC_DEMO ? [] : junctions}
          traffic={STATIC_DEMO ? null : traffic}
          trafficUnavailable={trafficUnavailable}
          showTrafficOverlay={!STATIC_DEMO}
          replay={replayFrames !== null}
        />
        <div className="sidebar">
          <section>
            <h2>Approval queue</h2>
            <ApprovalQueue
              incidents={incidents}
              selectedId={selectedId}
              onSelectIncident={setSelectedId}
              onApprove={handleApprove}
              onReject={handleReject}
              busyId={busyId}
              readOnly={STATIC_DEMO}
            />
          </section>
          {!STATIC_DEMO && (
            <section>
              <h2>Signal control</h2>
              <SignalControl
                junctions={traffic?.junctions}
                availableModes={liveTraffic?.available_modes}
                canControl={operatorToken.length > 0 && replayFrames === null}
                busyId={busyId}
                onSetMode={handleSetMode}
              />
            </section>
          )}
          <section>
            <h2>Explanation (XAI panel)</h2>
            <XaiPanel
              incident={selected}
              impact={selected ? (traffic?.impacts?.[selected.incident_id] ?? null) : null}
            />
          </section>
          <section>
            <h2>Replay scrubber</h2>
            <ReplayScrubber
              available={!STATIC_DEMO && liveTraffic?.ready === true}
              frames={replayFrames}
              index={replayIndex}
              playing={replayPlaying}
              loading={replayLoading}
              error={replayError}
              onStart={handleStartReplay}
              onSeek={(i) => {
                setReplayIndex(i);
                setReplayPlaying(false);
              }}
              onTogglePlay={() => setReplayPlaying((p) => !p)}
              onExit={handleExitReplay}
            />
          </section>
        </div>
      </main>
    </div>
  );
}

export default App;
